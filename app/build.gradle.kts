// Optional stable signing key (so app updates install over each other).
// Set RELEASE_KEYSTORE / RELEASE_KEYSTORE_PASSWORD / RELEASE_KEY_ALIAS / RELEASE_KEY_PASSWORD;
// otherwise the release APK is signed with the debug key.
val releaseKeystore: String? = System.getenv("RELEASE_KEYSTORE")?.takeIf { it.isNotBlank() }


    buildFeatures {
        compose = true
    }

    packaging {
        // yt-dlp, python, ffmpeg and aria2c ship as executables inside jniLibs;
        // they must be extracted to nativeLibraryDir to be runnable.
        jniLibs {
            useLegacyPackaging = true
        }
    }
}

